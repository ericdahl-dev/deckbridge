#!/usr/bin/env python3
"""Writes the picture's shared numbers (#571) from layout/layout.json for both languages.
Usage: gen_layout.py layout.json C_OUT SWIFT_OUT. Fails on an unknown kind or a malformed value."""
import json, re, sys


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def c_literal(kind, value):
    if kind == "color":
        if not re.fullmatch(r"[0-9A-F]{6}", value):
            raise SystemExit(f"bad color {value!r}")
        return f"0x{value}u"
    if kind in ("float", "ratio"):
        float(value)
        return (value + ".0f") if re.fullmatch(r"-?\d+", value) else value + "f"
    if kind == "int":
        int(value)
        return value
    if kind == "double":
        float(value)
        return value
    raise SystemExit(f"unknown kind {kind!r}")


def swift_line(name, kind, value):
    if kind == "color":
        return f"public static let {name} = 0x{value}"
    if kind in ("float", "ratio", "double"):
        return f"public static let {name}: Double = {value}"
    if kind == "int":
        return f"public static let {name} = {value}"
    raise SystemExit(f"unknown kind {kind!r}")


def main():
    source, c_out, swift_out = sys.argv[1:4]
    constants = json.load(open(source))["constants"]
    names = [c["name"] for c in constants]
    if len(set(names)) != len(names):
        raise SystemExit("a name is used twice")
    head = "Generated by tools/lc6000-display-fw/layout/gen_layout.py from layout/layout.json (#571). Don't edit; " \
           "regenerate with `make -C tools/lc6000-display-fw layout`."
    c = [f"// {head}", "#ifndef DFW_LAYOUT_GENERATED_H", "#define DFW_LAYOUT_GENERATED_H", ""]
    for k in constants:
        c.append(f"/// {k['about']}")
        c.append(f"#define DFW_{snake(k['name'])} {c_literal(k['kind'], k['value'])}")
    c += ["", "#endif", ""]
    swift = [f"// {head}", "", "/// The drawn jog display's picture: the numbers the Swift renderer and the chip's C share.",
             "public enum JogLayout {"]
    for k in constants:
        swift.append(f"    /// {k['about']}")
        swift.append(f"    {swift_line(k['name'], k['kind'], k['value'])}")
    swift += ["}", ""]
    open(c_out, "w").write("\n".join(c))
    open(swift_out, "w").write("\n".join(swift))


if __name__ == "__main__":
    main()
