// Writes src/band_table.c (#558): the progress ring's band per pixel, from band_geometry.h, the same code draw_band.c
// ran per pixel on every present before. Built and run by `make tables`; the tests check its output is current.
// Floats are written in C99's hex form, so they read back bit for bit.
#include <stdio.h>
#include <stdlib.h>

#include "band_geometry.h"

int main(void) {
    printf("// Generated by gen/band_table_gen.c from src/band_geometry.h (#558). Don't edit; regenerate with `make tables`.\n");
    printf("#include \"band_table.h\"\n\nconst dfw_band_entry dfw_band_table[] = {\n");
    int count = 0;
    for (int y = (int)CENTER - REACH; y <= (int)CENTER + REACH; y++)
        for (int x = (int)CENTER - REACH; x <= (int)CENTER + REACH; x++) {
            float band, start;
            dfw_pixel track;
            int ring = band_shape(x, y, &band, &start, &track);
            int layer = !in_frame(x, y) && band_clear(x, y);
            if (ring && !in_frame(x, y) && !layer) {
                fprintf(stderr, "(%d, %d): the band reaches outside its clear annulus\n", x, y);
                return 1;
            }
            if (!ring && !layer) continue;
            printf("    { %d, %d, %d, %d, %af, %af, 0x%06Xu },\n", x, y, ring, layer, (double)band, (double)start,
                   (unsigned)track);
            count++;
        }
    printf("};\n\nconst int dfw_band_entries = %d;\n", count);
    return 0;
}
