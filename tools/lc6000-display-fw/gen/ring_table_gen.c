// Writes src/ring_table.c (#558): the beat ring per pixel, from src/ring_geometry.h, the code draw.c's ring() and
// draw_live.c's lit_section() ran over the whole frame on every draw before. Built and run by `make tables`; the tests
// check its output is current.
#include <stdio.h>
#include <string.h>

#include "ring_geometry.h"

#define N (DFW_SIZE * DFW_SIZE)
static dfw_pixel normal[N], dark[N], lit[5][N];
static uint8_t touched[N], lit_touched[5][N];

static int gray(dfw_pixel p) { return (p & 0xFF) == (p >> 8 & 0xFF) && (p & 0xFF) == (p >> 16 & 0xFF); }

int main(void) {
    static uint8_t dark_touched[N];
    for (int i = 0; i < N; i++) normal[i] = dark[i] = GROUND;
    ring_geometry(normal, 0, touched);
    ring_geometry(dark, 1, dark_touched);
    if (memcmp(touched, dark_touched, sizeof touched) != 0) { fprintf(stderr, "the dark ring touches other pixels\n"); return 1; }
    for (int beat = 1; beat <= 4; beat++) {
        for (int i = 0; i < N; i++) lit[beat][i] = GROUND;
        lit_geometry(lit[beat], beat, lit_touched[beat]);
    }
    printf("// Generated by gen/ring_table_gen.c from src/ring_geometry.h (#558). Don't edit; regenerate with `make tables`.\n");
    printf("#include \"ring_table.h\"\n\nconst dfw_ring_entry dfw_ring_table[] = {\n");
    int count = 0;
    for (int i = 0; i < N; i++) {
        int beat = 0;
        for (int b = 1; b <= 4; b++)
            if (lit_touched[b][i]) {
                if (beat || !touched[i]) { fprintf(stderr, "pixel %d: a lit section the ring doesn't hold\n", i); return 1; }
                beat = b;
            }
        if (!touched[i]) continue;
        if (!gray(normal[i]) || !gray(dark[i])) { fprintf(stderr, "pixel %d: not a gray\n", i); return 1; }
        dfw_pixel l = beat ? lit[beat][i] : 0;
        printf("    { %d, %u, %u, %d, %u, %u, %u },\n", i, (unsigned)(normal[i] & 0xFF), (unsigned)(dark[i] & 0xFF), beat,
               (unsigned)(l >> 16 & 0xFF), (unsigned)(l >> 8 & 0xFF), (unsigned)(l & 0xFF));
        count++;
    }
    printf("};\n\nconst int dfw_ring_entries = %d;\n", count);
    return 0;
}
